def euclidean_distance(lat1, lng1, lat2, lng2):
    return math.sqrt((lat2 - lat1) ** 2 + (lng2 - lng1) ** 2)

def classify_by_coordinate(lat, lng, pass_num=1):
    """根據座標判斷國家和城市"""
    try:
        lat = float(lat)
        lng = float(lng)
    except:
        return None, None

    # 判斷國家
    country = None
    for c, ranges in COUNTRY_RANGES.items():
        lng_min, lng_max = ranges['lng']
        lat_min, lat_max = ranges['lat']
        if lng_min <= lng <= lng_max and lat_min <= lat <= lat_max:
            country = c
            break

    if not country:
        return None, None

    # 判斷第二級 (縣/市/州/省)
    city = None

    if country == '台灣':
        # 查詢最近的縣市
        min_dist = float('inf')
        for district_name, data in TAIWAN_DISTRICTS.items():
            lng_min, lng_max = data['lng']
            lat_min, lat_max = data['lat']
            if lng_min <= lng <= lng_max and lat_min <= lat <= lat_max:
                city = district_name
                break
        if not city:
            # 用距離找最近的
            for district_name, data in TAIWAN_DISTRICTS.items():
                c_lng, c_lat = data['center']
                dist = euclidean_distance(lat, lng, c_lat, c_lng)
                if dist < min_dist:
                    min_dist = dist
                    city = district_name

    elif country == '日本':
        # 查詢最近的都道府縣
        min_dist = float('inf')
        for pref_name, data in JAPAN_PREFECTURES.items():
            lng_min, lng_max = data['lng']
            lat_min, lat_max = data['lat']
            if lng_min <= lng <= lng_max and lat_min <= lat <= lat_max:
                city = pref_name
                break
        if not city:
            # 用距離找最近的
            for pref_name, data in JAPAN_PREFECTURES.items():
                c_lng, c_lat = data['center']
                dist = euclidean_distance(lat, lng, c_lat, c_lng)
                if dist < min_dist:
                    min_dist = dist
                    city = pref_name

    elif country == '中國':
        # 查詢最近的省份
        min_dist = float('inf')
        for prov_name, data in CHINA_PROVINCES.items():
            lng_min, lng_max = data['lng']
            lat_min, lat_max = data['lat']
            if lng_min <= lng <= lng_max and lat_min <= lat <= lat_max:
                city = prov_name
                break
        if not city:
            # 用距離找最近的
            for prov_name, data in CHINA_PROVINCES.items():
                c_lng, c_lat = data['center']
                dist = euclidean_distance(lat, lng, c_lat, c_lng)
                if dist < min_dist:
                    min_dist = dist
                    city = prov_name

    return country, city

def run_pass(pass_num):
    """執行一輪分類"""
    print("=" * 70, flush=True)
    print(f"🗺️  Pass {pass_num}: 座標範圍判斷分類", flush=True)
    print("=" * 70, flush=True)

    # 讀取所有檔案
    rows = []
    with open(CSV_FILE, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t')
        for row in reader:
            rows.append(row)

    total = len(rows)
    print(f"📊 讀取 {total} 個檔案\n", flush=True)

    success_count = 0
    fail_count = 0
    fail_by_country = defaultdict(list)
    updated_rows = []

    for i, row in enumerate(rows, 1):
        lng = row['經度'].strip()
        lat = row['緯度'].strip()

        # 根據座標判斷
        country, city = classify_by_coordinate(lat, lng, pass_num)

        if country:
            row['城市'] = city or ''
            row['國家'] = country
            success_count += 1
        else:
            fail_count += 1
            title = row['標題'][:30]
            fail_by_country['未知'].append((lat, lng, title))

        updated_rows.append(row)

        # 每 200 個顯示進度
        if i % 200 == 0 or i == 1:
            print(f"[{i:4d}/{total}] 進度: {i/total*100:5.1f}% | 成功: {success_count} | 失敗: {fail_count}", flush=True)

    # 寫回 CSV
    print("\n💾 寫入 CSV...", flush=True)
    with open(CSV_FILE, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['標題', '經度', '緯度', '城市', '國家'], delimiter='\t')
        writer.writeheader()
        writer.writerows(updated_rows)

    print("\n" + "=" * 70, flush=True)
    print(f"✅ Pass {pass_num} 完成！", flush=True)
    print(f"  成功分類: {success_count} 個 ({success_count*100//total}%)", flush=True)
    print(f"  無法分類: {fail_count} 個 ({fail_count*100//total}%)", flush=True)
    print("=" * 70, flush=True)

    return success_count, fail_count, rows

