def create_all_districts():
    """為所有縣市建立行政區目錄"""
    created_count = 0
    taiwan_path = os.path.join(WIKI_DIR, "台灣")

    for county, districts in TAIWAN_COMPLETE.items():
        county_path = os.path.join(taiwan_path, county)

        # 確保縣市目錄存在
        os.makedirs(county_path, exist_ok=True)

        for district in districts:
            district_path = os.path.join(county_path, district)

            # 如果行政區目錄不存在，建立它
            if not os.path.exists(district_path):
                os.makedirs(district_path, exist_ok=True)
                created_count += 1
                print(f"  ✓ {county}/{district}")

    return created_count

def main():
    print("=" * 70)
    print("📂 為所有台灣行政區建立目錄結構")
    print("=" * 70)
    print()

    created = create_all_districts()
    print()

    print("=" * 70)
    print(f"✅ 完成！建立了 {created} 個行政區目錄")
    print("=" * 70)
    print()
    print("台灣 22 縣市預備完成：")
    for county in TAIWAN_COMPLETE.keys():
        print(f"  ✓ {county}")

if __name__ == "__main__":
    main()
