def restructure_japan():
    """重新組織日本檔案為都道府縣/市區町村結構"""
    japan_path = os.path.join(WIKI_DIR, "日本")
    moved_count = 0
    unmapped_count = 0

    # 取得所有現有城市目錄
    existing_cities = [d for d in os.listdir(japan_path)
                      if os.path.isdir(os.path.join(japan_path, d))]

    for city in existing_cities:
        city_path = os.path.join(japan_path, city)
        prefecture = JAPAN_CITY_TO_PREFECTURE.get(city)

        if not prefecture:
            print(f"  ⚠️  無法找到都道府縣: {city}")
            unmapped_count += 1
            continue

        # 建立都道府縣目錄
        prefecture_path = os.path.join(japan_path, prefecture)
        os.makedirs(prefecture_path, exist_ok=True)

        # 建立市區町村目錄
        target_city_path = os.path.join(prefecture_path, city)
        os.makedirs(target_city_path, exist_ok=True)

        # 移動檔案
        if not os.path.exists(target_city_path) or len(os.listdir(target_city_path)) == 0:
            try:
                # 從原位置複製檔案到新位置
                for file in os.listdir(city_path):
                    src = os.path.join(city_path, file)
                    dst = os.path.join(target_city_path, file)
                    if os.path.isfile(src):
                        shutil.copy2(src, dst)
                        moved_count += 1

                # 刪除原目錄
                shutil.rmtree(city_path)
                print(f"  ✓ {prefecture}/{city}")
            except Exception as e:
                print(f"  ❌ 錯誤: {city} - {e}")

    return moved_count, unmapped_count

def main():
    print("=" * 70)
    print("🗂️ 重新組織日本檔案為都道府縣/市區町村結構")
    print("=" * 70)
    print()

    moved, unmapped = restructure_japan()
    print()

    print("=" * 70)
    print(f"✅ 完成！{moved} 個檔案已重新組織")
    if unmapped > 0:
        print(f"⚠️  {unmapped} 個城市無法對應都道府縣")
    print("=" * 70)

if __name__ == "__main__":
    main()
