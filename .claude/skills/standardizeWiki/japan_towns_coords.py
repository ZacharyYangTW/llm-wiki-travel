def get_nearest_town(file_coords, prefecture_name):
    """根據檔案座標找到最接近的市町村"""
    if prefecture_name not in JAPAN_TOWNS_COORDS:
        return None

    import math

    towns = JAPAN_TOWNS_COORDS[prefecture_name]
    min_distance = float('inf')
    nearest_town = None

    for town_name, town_coords in towns.items():
        # 歐氏距離計算（簡化版，未考慮地球曲率）
        distance = math.sqrt((file_coords[0] - town_coords[0])**2 + (file_coords[1] - town_coords[1])**2)
        if distance < min_distance:
            min_distance = distance
            nearest_town = town_name

    return nearest_town
