def get_nearest_county(coords):
    """根據座標找到最近的縣市"""
    if coords is None:
        return None

    lng, lat = coords
    min_distance = float('inf')
    nearest_county = None

    for county, (county_lng, county_lat) in TAIWAN_COUNTIES_COORDS.items():
        distance = ((lng - county_lng) ** 2 + (lat - county_lat) ** 2) ** 0.5
        if distance < min_distance:
            min_distance = distance
            nearest_county = county

    return nearest_county

def get_nearest_district(coords, county):
    """根據座標在某個縣市內找到最近的鄉鎮市區"""
    if coords is None or county not in TAIWAN_DISTRICTS_COORDS:
        return None

    lng, lat = coords
    districts = TAIWAN_DISTRICTS_COORDS[county]
    min_distance = float('inf')
    nearest_district = None

    for district_name, (district_lng, district_lat) in districts.items():
        distance = ((lng - district_lng) ** 2 + (lat - district_lat) ** 2) ** 0.5
        if distance < min_distance:
            min_distance = distance
            nearest_district = district_name

    return nearest_district
