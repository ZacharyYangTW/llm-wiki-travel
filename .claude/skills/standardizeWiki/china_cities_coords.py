def get_nearest_province(coords):
    """根據座標找到最近的省份"""
    if coords is None:
        return None

    lng, lat = coords

    # 特殊處理澳門和香港（優先於廣東省計算）
    macao_dist = ((lng - 113.5439) ** 2 + (lat - 22.1987) ** 2) ** 0.5
    hongkong_dist = ((lng - 114.1733) ** 2 + (lat - 22.3193) ** 2) ** 0.5

    if macao_dist < 0.5:  # 澳門半徑
        return "澳門"
    if hongkong_dist < 0.5:  # 香港半徑
        return "香港"

    min_distance = float('inf')
    nearest_prov = None

    for prov, (prov_lng, prov_lat) in CHINA_PROVINCES_COORDS.items():
        if prov in ["澳門", "香港"]:
            continue
        distance = ((lng - prov_lng) ** 2 + (lat - prov_lat) ** 2) ** 0.5
        if distance < min_distance:
            min_distance = distance
            nearest_prov = prov

    return nearest_prov

def get_nearest_city(coords, province):
    """根據座標在某個省份內找到最近的城市"""
    if coords is None or province not in CHINA_CITIES_COORDS:
        return None

    lng, lat = coords
    cities = CHINA_CITIES_COORDS[province]
    min_distance = float('inf')
    nearest_city = None

    for city_name, (city_lng, city_lat) in cities.items():
        distance = ((lng - city_lng) ** 2 + (lat - city_lat) ** 2) ** 0.5
        if distance < min_distance:
            min_distance = distance
            nearest_city = city_name

    return nearest_city
